CREATE TABLE funding_accounts (
    code VARCHAR(40) PRIMARY KEY,
    currency VARCHAR(3) NOT NULL,
    CONSTRAINT chk_funding_account_simulation
        CHECK (code = 'SIMULATED_MYR_SETTLEMENT' AND currency = 'MYR')
);

