CREATE TABLE funding_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(50) NOT NULL UNIQUE,
    wallet_id BIGINT NOT NULL REFERENCES wallets(id),
    operation_type VARCHAR(12) NOT NULL CHECK (operation_type IN ('DEPOSIT', 'WITHDRAWAL')),
    status VARCHAR(12) NOT NULL CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    amount BIGINT NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL CHECK (currency = 'MYR'),
    description VARCHAR(500),
    idempotency_key VARCHAR(255) NOT NULL,
    provider_reference VARCHAR(80) NOT NULL UNIQUE,
    provider_event_reference VARCHAR(100) UNIQUE,
    created_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ,
    CONSTRAINT uq_funding_wallet_type_key UNIQUE (wallet_id, operation_type, idempotency_key),
    CONSTRAINT chk_funding_resolution CHECK (
        (status = 'PENDING' AND provider_event_reference IS NULL AND resolved_at IS NULL)
        OR (status IN ('COMPLETED', 'FAILED') AND provider_event_reference IS NOT NULL AND resolved_at IS NOT NULL)
    )
);

CREATE INDEX idx_funding_wallet_activity ON funding_operations (wallet_id, created_at DESC, id DESC);

CREATE TABLE funding_ledger_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id BIGINT NOT NULL REFERENCES funding_operations(id),
    wallet_id BIGINT REFERENCES wallets(id),
    account_code VARCHAR(40) REFERENCES funding_accounts(code),
    entry_type VARCHAR(6) NOT NULL CHECK (entry_type IN ('DEBIT', 'CREDIT')),
    amount BIGINT NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL CHECK (currency = 'MYR'),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT chk_funding_entry_account CHECK ((wallet_id IS NULL) <> (account_code IS NULL)),
    CONSTRAINT uq_funding_operation_entry_type UNIQUE (operation_id, entry_type)
);
