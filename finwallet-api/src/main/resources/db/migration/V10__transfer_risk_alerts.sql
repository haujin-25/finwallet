CREATE TABLE transfer_risk_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT NOT NULL REFERENCES transfers(id),
    rule VARCHAR(40) NOT NULL CHECK (rule IN ('LARGE_TRANSFER', 'RAPID_TRANSFERS', 'DISTINCT_RECIPIENTS')),
    occurred_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_transfer_risk_alert_rule UNIQUE (transfer_id, rule)
);

CREATE INDEX idx_transfer_risk_alert_order ON transfer_risk_alerts (occurred_at DESC, id DESC);
