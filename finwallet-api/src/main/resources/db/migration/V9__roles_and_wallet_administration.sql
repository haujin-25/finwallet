ALTER TABLE users
    ADD COLUMN role VARCHAR(20) NOT NULL DEFAULT 'ROLE_USER',
    ADD CONSTRAINT chk_users_role CHECK (role IN ('ROLE_USER', 'ROLE_ADMIN'));

ALTER TABLE wallets
    DROP CONSTRAINT chk_wallets_status,
    ADD CONSTRAINT chk_wallets_status CHECK (status IN ('ACTIVE', 'FROZEN', 'SUSPENDED', 'CLOSED'));

CREATE TABLE admin_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    administrator_user_id BIGINT NOT NULL REFERENCES users (id),
    action VARCHAR(20) NOT NULL,
    wallet_id BIGINT NOT NULL REFERENCES wallets (id),
    occurred_at TIMESTAMPTZ NOT NULL,
    reason VARCHAR(500) NOT NULL CHECK (btrim(reason) <> ''),
    previous_status VARCHAR(20) NOT NULL CHECK (previous_status IN ('ACTIVE', 'FROZEN')),
    new_status VARCHAR(20) NOT NULL,
    outcome VARCHAR(20) NOT NULL,
    CONSTRAINT chk_admin_audit_action CHECK (
        (action = 'FREEZE' AND new_status = 'FROZEN')
        OR (action = 'UNFREEZE' AND new_status = 'ACTIVE')
    ),
    CONSTRAINT chk_admin_audit_outcome CHECK (
        (outcome = 'APPLIED' AND previous_status <> new_status)
        OR (outcome = 'NO_CHANGE' AND previous_status = new_status)
    )
);

CREATE INDEX idx_admin_audit_order ON admin_audit_logs (occurred_at DESC, id DESC);
